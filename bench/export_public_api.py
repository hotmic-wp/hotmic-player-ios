#!/usr/bin/env python3
"""Export the partner API from a compiled module, excluding Benchmark SPI."""
import argparse
import json
import pathlib
import subprocess

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--module-dir', required=True)
parser.add_argument('--output', default='docs/PUBLIC_API.md')
parser.add_argument('--graphs', default='.bench/review-symbolgraphs')
args = parser.parse_args()
graphs = pathlib.Path(args.graphs)
graphs.mkdir(parents=True, exist_ok=True)
sdk = subprocess.check_output(['xcrun', '--sdk', 'iphonesimulator', '--show-sdk-path'], text=True).strip()
subprocess.run(['xcrun', 'swift-symbolgraph-extract', '-module-name', 'HotMicPlayer',
                '-target', 'arm64-apple-ios17.0-simulator', '-sdk', sdk, '-I', args.module_dir,
                '-minimum-access-level', 'public', '-skip-synthesized-members', '-output-dir', str(graphs)], check=True)
symbols = {}
for file in graphs.glob('HotMicPlayer*.symbols.json'):
    for symbol in json.loads(file.read_text())['symbols']:
        if 'location' in symbol and not symbol.get('isSPI', False):
            symbols[symbol['identifier']['precise']] = symbol
missing_docs = [s['pathComponents'] for s in symbols.values() if not s.get('docComment')]
if missing_docs:
    raise SystemExit(f'Exported symbols without documentation: {missing_docs}')
groups = {}
for symbol in symbols.values():
    path = symbol['pathComponents']
    kind = symbol['kind']['identifier']
    name = '.'.join(path if kind in {'swift.struct', 'swift.class', 'swift.enum', 'swift.protocol'} else path[:-1])
    declaration = ''.join(f['spelling'] for f in symbol['declarationFragments'])
    groups.setdefault(name, set()).add(declaration)
lines = ['# Public API inventory — 0.2.0', '',
         'Generated by `bench/export_public_api.py` from the compiled iOS simulator module. Benchmark SPI and synthesized members are excluded. Every explicitly exported type, function, initializer, property and enum case is listed, including analytics/timeline contracts. Snapshot setters are internal; compiler fragments may omit that restriction. Behavioral contracts are in [Integration](INTEGRATION.md).', '']
for name, declarations in sorted(groups.items()):
    lines += [f'## {name}', '', '```swift', *sorted(declarations), '```', '']
pathlib.Path(args.output).write_text('\n'.join(lines))
print(f'{len(symbols)} documented non-SPI symbols, {len(groups)} groups -> {args.output}')
